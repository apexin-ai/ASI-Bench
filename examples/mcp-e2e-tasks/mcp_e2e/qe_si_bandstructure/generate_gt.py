"""Instance generator for the quantum_espresso silicon band-structure MCP E2E fake task.

A seeded RNG picks a plane-wave cutoff, a k-point spacing and a number of
band-path points. Through the qe-mcp server (Quantum ESPRESSO 7.5) the agent
must drive a five-tool chain on silicon:

    qe_list_pseudopotentials -> qe_suggest_kpoints -> qe_workflow_bandstructure
                             -> qe_list_files -> qe_read_bands

where every step feeds the next: the suggested grid is the band-structure
run's SCF grid, the run's directory is what gets listed, and the band file
the listing returns is what gets read. The answer is the run's energies and
band edges plus what the band file and the pseudopotential index say.

Where the reference comes from
------------------------------
DFT cannot be recomputed here: ``pw.x`` and ``bands.x`` exist only inside the
server's pinned conda environment, and a task runtime may not build one. The
DFT numbers are therefore **measured** against that environment by
``scripts/mcp/e2e/measure_qe_table.py`` and carried in ``MEASURED`` below,
keyed by ``(ecutwfc, grid, npoints_band)`` — the three things the calculation
depends on. Everything else is derived here, in the standard library:

* the SCF grid from the k-spacing, by the server's documented rule
  (``ceil(1 / (|a_i| * kspacing))`` snapped to the nearest odd count, the
  larger on a tie), on the built-in silicon cell — reconciled with the
  server's own ``qe_suggest_kpoints`` answers the table records;
* ``n_bands`` (8 per atom) and ``n_kpoints`` (the number of path points).

Generation refuses an instance whose measured record contradicts any of this,
so the reference is never quietly inconsistent with the server.

Two upstream properties that shape the reference
------------------------------------------------
* Which pseudopotential file an element gets follows the host's directory
  order (D1 in the smoke). The table records the Si file it was measured with
  and the reference carries it: the agent reports the file the server indexes,
  so a host that picks differently shows up as a wrong ``si_pseudopotential``
  instead of as unexplained energy differences. Measured on aarch64 and amd64:
  both pick ``Si_ONCV_PBE-1.2.upf``.
* The density cutoff is never on the MCP surface: the server keeps ``ecutrho``
  at the hint table's 120 Ry whatever ``ecutwfc`` is. The cutoffs stay at or
  below 30 Ry so the density cutoff is at least four times the wavefunction
  cutoff, as norm-conserving pseudopotentials need.

Framework call: python generate_gt.py --output-dir <dir> --params '<json>'
Standard library only.
"""
