class GenerationError(RuntimeError):
    pass


# ---------------------------------------------------------------------------
# The k-grid policy (structures.suggest_kpoints with an explicit kspacing)
# ---------------------------------------------------------------------------

def si_cell_length() -> float:
    """|a_i| of the primitive fcc cell of diamond silicon: a / sqrt(2)."""
    return SI_A / math.sqrt(2.0)


def snap_odd(n: int) -> int:
    """Nearest value of PREFERRED_KPTS, the larger one on a tie."""
    if n <= 1:
        return 1
    if n >= PREFERRED_KPTS[-1]:
        return PREFERRED_KPTS[-1]
    return min(PREFERRED_KPTS, key=lambda p: (abs(n - p), -p))


def kgrid(kspacing: float) -> list[int]:
    raw = 1.0 / (si_cell_length() * kspacing)
    if abs(raw - round(raw)) < CEIL_MARGIN:
        raise GenerationError(f"1/(|a| kspacing) = {raw:.4f} is too close to an integer for "
                              f"kspacing={kspacing}; the grid would hang on rounding")
    return [snap_odd(max(1, math.ceil(raw)))] * 3


