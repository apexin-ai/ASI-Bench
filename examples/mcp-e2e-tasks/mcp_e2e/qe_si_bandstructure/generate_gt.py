def build_case(seed: int) -> dict:
    rng = random.Random(seed)
    return {
        "structure": STRUCTURE,
        "ecutwfc": ECUTWFC[rng.randrange(len(ECUTWFC))],
        "kspacing": KSPACING[rng.randrange(len(KSPACING))],
        "npoints_band": NPOINTS_BAND[rng.randrange(len(NPOINTS_BAND))],
        "result_file": "result.json",
    }


def reference(case: dict) -> dict:
    if case["ecutwfc"] * 4 > ECUTRHO_RY:
        raise GenerationError(f"ecutwfc={case['ecutwfc']} Ry with the fixed ecutrho={ECUTRHO_RY} Ry "
                              "is below the norm-conserving dual of 4")
    grid = kgrid(case["kspacing"])
    suggested = MEASURED["suggested_grid_by_kspacing"].get(repr(case["kspacing"]))
    if suggested != grid:
        raise GenerationError(f"the grid rule gives {grid} for kspacing={case['kspacing']} but the "
                              f"server suggested {suggested}")
    point = (case["ecutwfc"], grid[0], case["npoints_band"])
    measured = MEASURED["points"].get(point)
    if measured is None:
        raise GenerationError(f"no measured run for (ecutwfc, grid, npoints_band) = {point}; "
                              "regenerate MEASURED with scripts/mcp/e2e/measure_qe_table.py "
                              f"(have {sorted(MEASURED['points'])})")

    pseudo = MEASURED["si_pseudopotential"]
    problems = []
    if measured["pseudo_copied"] != [pseudo]:
        problems.append(f"the run copied {measured['pseudo_copied']}, the index says {pseudo}")
    if measured["n_bands"] != 8 * N_ATOMS:
        problems.append(f"n_bands {measured['n_bands']} != 8 x {N_ATOMS}")
    if not measured["n_kpoints"] == measured["read_n_kpoints"] == case["npoints_band"]:
        problems.append(f"n_kpoints {measured['n_kpoints']} / read {measured['read_n_kpoints']} "
                        f"!= npoints_band {case['npoints_band']}")
    if measured["file_names"] != list(RUN_FILES):
        problems.append(f"the run left {measured['file_names']}, expected {list(RUN_FILES)}")
    if measured["is_metal"] or measured["band_gap_eV"] is None or measured["band_gap_eV"] <= 0:
        problems.append("no band gap")
    elif abs(measured["cbm_eV"] - measured["vbm_eV"] - measured["band_gap_eV"]) > 1e-9:
        problems.append("band_gap_eV is not cbm_eV - vbm_eV")
    if problems:
        raise GenerationError(f"measured record {point} is inconsistent: " + "; ".join(problems))

    return {
        "si_pseudopotential": pseudo,
        "scf_kpoints": grid,
        "total_energy_eV": measured["total_energy_eV"],
        "fermi_energy_eV": measured["fermi_energy_eV"],
        "band_gap_eV": measured["band_gap_eV"],
        "vbm_eV": measured["vbm_eV"],
        "cbm_eV": measured["cbm_eV"],
        "is_direct_gap": measured["is_direct_gap"],
        "n_bands": measured["n_bands"],
        "n_kpoints": measured["n_kpoints"],
        "path_length": measured["path_length"],
        # What the verifier compares qe_list_files against (a subset of the listing).
        "file_names": list(RUN_FILES),
        "ecutrho_ry": ECUTRHO_RY,
        "n_atoms": N_ATOMS,
        "mcp_tools": list(MCP_TOOLS),
    }


